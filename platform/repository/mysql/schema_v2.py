def apply_schema(connection) -> list[str]:
    """Apply V2 tables to an already selected STORY_OS_RUNTIME connection.

    This function is not called from application startup.  Migration tooling
    must opt in explicitly after lower_case_table_names and target database
    checks have passed.
    """
    applied: list[str] = []
    for step, sql in DDL_STEPS:
        connection.execute(sql)
        applied.append(step)
    return applied
